import { IModelProvider, ModelExecutionOptions, ModelExecutionResult, ModelProviderError } from '../types';

export const DEFAULT_CLOUDFLARE_MODEL = '@cf/meta/llama-3.1-8b-instruct-fast';

export class CloudflareWorkersAiProvider implements IModelProvider {
  readonly id = 'cloudflare';
  readonly name = 'Cloudflare Workers AI';
  private aiBinding?: Ai;
  private defaultModel: string;

  constructor(aiBinding?: Ai, defaultModel: string = DEFAULT_CLOUDFLARE_MODEL) {
    this.aiBinding = aiBinding;
    this.defaultModel = defaultModel;
  }

  isConfigured(): boolean {
    return Boolean(this.aiBinding);
  }

  supportsModel(modelId: string): boolean {
    // Matches native cloudflare models or default orbit agent IDs
    return (
      modelId.startsWith('@cf/') ||
      modelId === 'orbit-agent-v2' ||
      modelId === this.defaultModel ||
      modelId === 'default'
    );
  }

  async execute(options: ModelExecutionOptions): Promise<ModelExecutionResult> {
    if (!this.aiBinding) {
      throw new ModelProviderError(
        'Cloudflare Workers AI binding "AI" is not configured or unavailable on this Worker.',
        {
          code: 'AI_UNAVAILABLE',
          provider: this.id,
          statusCode: 503,
          isRetryable: false,
        }
      );
    }

    const targetModel =
      options.modelId && options.modelId.startsWith('@cf/')
        ? options.modelId
        : this.defaultModel;

    try {
      const response: any = await this.aiBinding.run(targetModel, {
        messages: options.messages,
        max_tokens: options.maxTokens || 1024,
      });

      let responseText = '';
      if (response && typeof response === 'object') {
        responseText = typeof response.response === 'string'
          ? response.response.trim()
          : JSON.stringify(response);
      } else if (typeof response === 'string') {
        responseText = response.trim();
      }

      if (!responseText) {
        responseText = 'I received your message, but no response was generated by the model.';
      }

      return {
        text: responseText,
        provider: this.id,
        modelId: targetModel,
      };
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : 'Workers AI execution error';
      throw new ModelProviderError(
        `Failed to generate response from Workers AI model: ${msg}`,
        {
          code: 'AI_GENERATION_FAILED',
          provider: this.id,
          statusCode: 502,
          isRetryable: true,
        }
      );
    }
  }
}
